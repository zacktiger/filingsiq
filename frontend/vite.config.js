import { defineConfig } from "vite";
import react from "@vitejs/plugin-react";

export default defineConfig({
  plugins: [react()],
  server: {
    port: 5173,
    // Proxy /api to FastAPI so the browser sees one origin in development.
    // The backend also sets CORS headers, but proxying means the frontend code
    // needs no absolute URLs and no separate config for dev vs production.
    proxy: {
      "/api": {
        target: "http://localhost:8000",
        changeOrigin: true,
        rewrite: (path) => path.replace(/^\/api/, ""),
      },
    },
  },
});
